const romsUsage = `usage: roms.py [-h] --configs CONFIGS [CONFIGS ...] --output OUTPUT
               [--game GAME] [--game-output GAME_OUTPUT]
               [--files-output FILES_OUTPUT]
`

const romsHelp = romsUsage + `
Compile game TOML manifests into immutable runtime chip tables (no ROM bytes).

options:
  -h, --help            show this help message and exit
  --configs CONFIGS [CONFIGS ...]
  --output OUTPUT
  --game GAME           F3_GAME id; with --game-output writes
                        game_video_config.hpp
  --game-output GAME_OUTPUT
  --files-output FILES_OUTPUT
                        Write the chip file names of --game, one per line
`

type NamedManifest struct {
	Path     string
	Manifest Manifest
}

func (n NamedManifest) GameID() (string, error) {
	id, ok := n.Manifest.GameID()
	if !ok {
		return "", fmt.Errorf("%s: missing game.id", n.Path)
	}
	return id, nil
}

type Manifests []NamedManifest

func LoadManifests(paths []string) (Manifests, error) {
	manifests := make(Manifests, len(paths))
	for i, path := range paths {
		manifest, err := LoadManifest(path)
		if err != nil {
			return nil, err
		}
		manifests[i] = NamedManifest{Path: path, Manifest: manifest}
	}
	return manifests, nil
}

func (m Manifests) GameConfig(game string) (GameConfig, error) {
	for _, named := range m {
		if id, err := named.GameID(); err != nil {
			return GameConfig{}, err
		} else if id == game {
			return GameConfig{Manifest: named.Manifest, Path: named.Path, ID: id}, nil
		}
	}
	return GameConfig{}, fmt.Errorf("no config declares game %s", game)
}

type ChipTable struct{ text string }

func (t *ChipTable) Write(path string) error {
	_, err := WriteIfChanged(path, []byte(t.text))
	return err
}

func (m Manifests) ChipTable() (*ChipTable, error) {
	var lines strings.Builder
	lines.WriteString("// Generated by recomp/compile/roms.py. No ROM data.\n#pragma once\n")
	lines.WriteString("#include \"f3rt/rom.hpp\"\n#include <array>\n#include <span>\n#include <string_view>\n")
	lines.WriteString("namespace f3rt::rom_manifest {\n")
	lines.WriteString("struct Chip { const char *file; size_t size; uint32_t crc; const char *sha1; size_t short_size; " +
		"uint32_t short_crc; const char *short_sha1; size_t offset, stride, group, source_offset, length; bool word_swap; };\n")
	lines.WriteString("struct Region { size_t size, mapped_size; uint8_t fill; std::span<const Chip> chips; };\n")
	lines.WriteString("struct Game { std::string_view id; std::string_view pref_dir; VideoConfig video; InputConfig input; bool sound_bankswitch; std::array<Region, 8> regions; };\n")
	var games []string
	ids := map[string]bool{}
	for index, named := range m {
		identity, err := named.GameID()
		if err != nil {
			return nil, err
		}
		if ids[identity] {
			return nil, fmt.Errorf("Duplicate game id: %s", identity)
		}
		ids[identity] = true
		var regions []string
		for _, name := range RegionNames {
			spec, err := named.Manifest.RegionSpec(name)
			if err != nil {
				if errors.Is(err, errMirrorSize) {
					return nil, fmt.Errorf("Invalid mirrored region size: %s: %s", named.Path, name)
				}
				return nil, err
			}
			table := fmt.Sprintf("chips_%d_%s", index, name)
			fmt.Fprintf(&lines, "inline constexpr std::array<Chip, %d> %s = {{\n", len(spec.Lanes), table)
			for _, chip := range spec.Lanes {
				shortCRC := chip.ShortCRC
				if chip.ShortSize == 0 {
					shortCRC = "0"
				}
				values := []string{
					Quote(chip.File),
					strconv.Itoa(chip.Size),
					"0x" + chip.CRC + "u",
					Quote(chip.SHA1),
					strconv.Itoa(chip.ShortSize),
					"0x" + shortCRC + "u",
					Quote(chip.ShortSHA1),
					strconv.Itoa(chip.Offset),
					strconv.Itoa(chip.Stride),
					strconv.Itoa(chip.Group),
					strconv.Itoa(chip.SourceOffset),
					strconv.Itoa(chip.Length),
					strconv.FormatBool(chip.WordSwap),
				}
				lines.WriteString("    { " + strings.Join(values, ", ") + " },\n")
			}
			lines.WriteString("}};\n")
			regions = append(regions, fmt.Sprintf("{ %d, %d, %d, %s }", spec.Size, spec.Mapped, spec.Fill, table))
		}
		videoSettings, err := videoSettings(named.Manifest, named.Path)
		if err != nil {
			return nil, err
		}
		inputSettings, err := inputSettings(named.Manifest, named.Path)
		if err != nil {
			return nil, err
		}
		bankswitch := strings.ToLower(Text(lookup(named.Manifest.Section("sound"), "bankswitch", false)))
		games = append(games, fmt.Sprintf("    { %s, %s, %s, %s, %s, {{ %s }} },\n",
			Quote(identity), Quote(prefDir(named.Manifest, identity)), videoSettings, inputSettings,
			bankswitch, strings.Join(regions, ", ")))
	}
	fmt.Fprintf(&lines, "inline constexpr std::array<Game, %d> games = {{\n", len(games))
	for _, game := range games {
		lines.WriteString(game)
	}
	lines.WriteString("}};\n} // namespace f3rt::rom_manifest\n")
	return &ChipTable{text: lines.String()}, nil
}

type GameConfig struct {
	Manifest Manifest
	Path     string
	ID       string
}

func (g GameConfig) Write(path string) error {
	settings, err := videoSettings(g.Manifest, g.Path)
	if err != nil {
		return err
	}
	inSettings, err := inputSettings(g.Manifest, g.Path)
	if err != nil {
		return err
	}
	text := fmt.Sprintf(`// Generated by recomp/compile/roms.py from games/%[1]s/config.toml. No ROM data.
#pragma once
#include <string_view>
#include "f3rt/rom.hpp"

namespace f3rt::game_config {
inline constexpr std::string_view id = %[2]s;
inline constexpr std::string_view pref_dir = %[3]s;
inline constexpr InputConfig input%[4]s;
inline constexpr VideoConfig video%[5]s;
inline constexpr unsigned visible_end = video.visible_y + video.visible_height;
static_assert(video.visible_y + video.visible_height <= 256 && video.visible_height > 0,
              "visible window must fit the 256-line frame");
static_assert(!video.full_resolution_alt_maps || video.extended_alt_maps,
              "full_resolution_alt_maps requires extended_alt_maps");
// Startup consistency check: a loaded set must carry the geometry this build was compiled for.
constexpr bool matches(const VideoConfig &v) {
    return v.rotation == video.rotation && v.sprite_lag == video.sprite_lag &&
           v.visible_y == video.visible_y && v.visible_height == video.visible_height &&
           v.extend == video.extend && v.extended_alt_maps == video.extended_alt_maps &&
           v.full_resolution_alt_maps == video.full_resolution_alt_maps;
}
} // namespace f3rt::game_config
`, g.ID, Quote(g.ID), Quote(prefDir(g.Manifest, g.ID)), inSettings, settings)
	_, err = WriteIfChanged(path, []byte(text))
	return err
}

func (g GameConfig) ChipFiles() ([]string, error) {
	var files []string
	for _, name := range RegionNames {
		spec, err := g.Manifest.RegionSpec(name)
		if err != nil {
			if errors.Is(err, errMirrorSize) {
				return nil, fmt.Errorf("Invalid mirrored region size: %s: %s", g.Path, name)
			}
			return nil, err
		}
		for _, chip := range spec.Lanes {
			if !slices.Contains(files, chip.File) {
				files = append(files, chip.File)
			}
		}
	}
	return files, nil
}

func prefDir(manifest Manifest, fallback string) string {
	if dir, ok := manifest.Section("game").String("pref_dir"); ok {
		return dir
	}
	return fallback
}

func lookup(manifest Manifest, key string, def any) any {
	if v, ok := manifest.Value(key); ok {
		return v
	}
	return def
}

func videoSettings(manifest Manifest, path string) (string, error) {
	video := manifest.Section("video")
	rotation, rotationOK := intValue(lookup(video, "rotation", 0))
	lag, lagOK := intValue(lookup(video, "sprite_lag", 1))
	y, yOK := intValue(lookup(video, "visible_y", 24))
	height, heightOK := intValue(lookup(video, "visible_height", 232))
	extend, extendOK := lookup(video, "extend", true).(bool)
	extendedAltMaps, extendedOK := lookup(video, "extended_alt_maps", false).(bool)
	fullResolutionAltMaps, fullOK := lookup(video, "full_resolution_alt_maps", false).(bool)
	if !rotationOK || !lagOK || !yOK || !heightOK || !extendOK || !extendedOK || !fullOK ||
		!slices.Contains([]int{0, 90, 180, 270}, rotation) || !slices.Contains([]int{0, 1, 2}, lag) ||
		!(0 <= y && y < y+height && y+height <= 256) {
		return "", fmt.Errorf("Unsupported video configuration: %s", path)
	}
	if fullResolutionAltMaps && !extendedAltMaps {
		return "", fmt.Errorf("video.full_resolution_alt_maps requires video.extended_alt_maps: %s", path)
	}
	return fmt.Sprintf("{ %d, %d, %d, %d, %s, %s, %s }", rotation, lag, y, height,
		strconv.FormatBool(extend), strconv.FormatBool(extendedAltMaps), strconv.FormatBool(fullResolutionAltMaps)), nil
}

func inputSettings(manifest Manifest, path string) (string, error) {
	input := manifest.Section("input")
	dial, dialOK := lookup(input, "dial", false).(bool)
	sixButton, sixOK := lookup(input, "six_button", false).(bool)
	if !dialOK || !sixOK {
		return "", fmt.Errorf("Unsupported input configuration: %s", path)
	}
	return fmt.Sprintf("{ %s, %s }", strconv.FormatBool(dial), strconv.FormatBool(sixButton)), nil
}

type RomsCommand struct {
	Configs     []string
	Output      string
	Game        string
	GameOutput  string
	FilesOutput string
}

func ParseRomsCommand(args []string) (RomsCommand, error) {
	command := RomsCommand{}
	var configs listFlag
	fs := newFlagSet("roms.py")
	fs.Var(&configs, "configs", "")
	output := fs.String("output", "", "")
	game := fs.String("game", "", "")
	gameOutput := fs.String("game-output", "", "")
	filesOutput := fs.String("files-output", "", "")
	if err := parseFlagSet(fs, args, []string{"configs", "output"}, []string{"configs"}); err != nil {
		return RomsCommand{}, err
	}
	command.Configs, command.Output = configs.values, *output
	command.Game, command.GameOutput, command.FilesOutput = *game, *gameOutput, *filesOutput
	if (command.Game != "") != (command.GameOutput != "") {
		return RomsCommand{}, &UsageError{Message: "--game and --game-output go together"}
	}
	if command.FilesOutput != "" && command.Game == "" {
		return RomsCommand{}, &UsageError{Message: "--files-output requires --game"}
	}
	return command, nil
}

func (c RomsCommand) Run(stdout, stderr io.Writer) int {
	manifests, err := LoadManifests(c.Configs)
	if err != nil {
		return romsFailure(stderr, err)
	}
	table, err := manifests.ChipTable()
	if err != nil {
		return romsFailure(stderr, err)
	}
	if err := table.Write(c.Output); err != nil {
		return romsFailure(stderr, err)
	}
	if c.Game == "" {
		return 0
	}
	game, err := manifests.GameConfig(c.Game)
	if err != nil {
		return romsFailure(stderr, err)
	}
	if err := game.Write(c.GameOutput); err != nil {
		return romsFailure(stderr, err)
	}
	if c.FilesOutput == "" {
		return 0
	}
	names, err := game.ChipFiles()
	if err != nil {
		return romsFailure(stderr, err)
	}
	var text strings.Builder
	for _, name := range names {
		text.WriteString(name + "\n")
	}
	if _, err := WriteIfChanged(c.FilesOutput, []byte(text.String())); err != nil {
		return romsFailure(stderr, err)
	}
	return 0
}

func runRoms(args []string, stdout, stderr io.Writer) int {
	command, err := ParseRomsCommand(args)
	if err != nil {
		return commandFailure(err, stdout, stderr, "roms.py", romsUsage, romsHelp)
	}
	return command.Run(stdout, stderr)
}

func romsFailure(stderr io.Writer, err error) int {
	fmt.Fprintf(stderr, "roms.py: %v\n", err)
	return 1
}
