type t = Config.emit_unit list

let of_config config = config.Config.video.emit_units

let hooks units =
  let add id map pc =
    Pc.Map.update pc
      (function None -> Some [id] | Some ids -> Some (id :: ids))
      map
  in
  List.fold_right
    (fun (unit : Config.emit_unit) (enter, leave) ->
      List.fold_left (add unit.id) enter unit.starts,
      List.fold_left (add unit.id) leave unit.ends)
    units (Pc.Map.empty, Pc.Map.empty)

let register_name = function
  | Config.Data index -> Printf.sprintf "d%d" index
  | Config.Address index -> Printf.sprintf "a%d" index

let canonical units =
  let pcs addresses = List.map (Printf.sprintf "%x") addresses |> String.concat "," in
  let row (unit : Config.emit_unit) =
    Printf.sprintf "%s|%s|%s|%s|%d"
      unit.name (pcs unit.starts) (pcs unit.ends) (register_name unit.reg) unit.size
  in
  "units:" ^ String.concat ";" (List.map row units) ^ "\n"

let digest units = Image.crc32 { base = 0; bytes = canonical units }

let guard_lines units =
  Printf.sprintf
    {|#include "sprite_units.h"
#if F3_SPRITE_UNITS_DIGEST != 0x%08lxu
#error "Generated program and sprite_units.h describe different emit units"
#endif
|}
    (digest units)

let banner = "/* Generated by recomp/compile/sprite_units.py from config.toml. Do not commit. */\n"

let c_header units =
  Printf.sprintf
    {|%s#ifndef F3_SPRITE_UNITS_H
#define F3_SPRITE_UNITS_H
#define F3_SPRITE_UNITS_DIGEST 0x%08lxu
#define F3_SPRITE_UNIT_COUNT %d
#endif
|}
    banner (digest units) (List.length units)

let cpp_header units =
  let out = Buffer.create 2048 in
  let line format = Printf.bprintf out format in
  let addresses name suffix pcs =
    let values = List.map (Printf.sprintf "0x%xu") pcs |> String.concat ", " in
    line "inline constexpr std::array<uint32_t, %d> %s_%s{%s};\n"
      (List.length pcs) name suffix values
  in
  line {|%s#pragma once
#include <array>
#include <cstddef>
#include <cstdint>
#include "f3rt/emit_unit.hpp"
#include "sprite_units.h"

namespace f3rt::sprite_units {

|} banner;
  if units <> [] then begin
    line "namespace detail {\n";
    List.iter
      (fun (unit : Config.emit_unit) ->
        addresses unit.name "starts" unit.starts;
        addresses unit.name "ends" unit.ends)
      units;
    line "} // namespace detail\n\n"
  end;
  List.iter
    (fun (unit : Config.emit_unit) ->
      line
        "inline constexpr EmitUnit %s{%du, %S, detail::%s_starts, detail::%s_ends, UnitRegister::%s, %du};\n"
        unit.name unit.id unit.name unit.name unit.name
        (String.uppercase_ascii (register_name unit.reg)) unit.size)
    units;
  let pointers =
    List.map (fun (unit : Config.emit_unit) -> "&" ^ unit.name) units
    |> String.concat ", "
  in
  line {|
inline constexpr std::array<const EmitUnit *, %d> all{%s};
inline constexpr uint32_t digest = F3_SPRITE_UNITS_DIGEST;

constexpr bool valid_units() {
    for (std::size_t i = 0; i < all.size(); ++i) {
        const EmitUnit &unit = *all[i];
        if (unit.id != i || unit.starts.size() == 0 || unit.starts.size() != unit.ends.size())
            return false;
        for (std::size_t j = 0; j < unit.starts.size(); ++j)
            if ((unit.starts[j] & 1u) || (unit.ends[j] & 1u) || unit.starts[j] >= unit.ends[j])
                return false;
    }
    return true;
}
static_assert(valid_units(), "emit unit ids must equal their index; PCs even, start < end, starts/ends of equal arity");
static_assert(all.size() == F3_SPRITE_UNIT_COUNT, "unit count mismatch");

} // namespace f3rt::sprite_units
|} (List.length units) pointers;
  Buffer.contents out

let render units =
  ["sprite_units.h", c_header units; "sprite_units.hpp", cpp_header units]
