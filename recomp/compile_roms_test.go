func chipConfig(id, extra string) string {
	data := []byte{1, 2, 3, 4}
	sum := sha1.Sum(data)
	return fmt.Sprintf(`
[game]
id = %q
%s
[rom]
size = 8
interleave = 2
[[rom.lanes]]
file = "even.bin"
offset = 0
size = 4
crc = "%08x"
sha1 = "%s"
[[rom.lanes]]
file = "odd.bin"
offset = 1
size = 4
crc = "%08x"
sha1 = "%s"
[sound]
size = 4
mirror_size = 8
bankswitch = true
[[sound.lanes]]
file = "even.bin"
size = 4
stride = 1
crc = "%08x"
sha1 = "%s"
`, id, extra, crc32.ChecksumIEEE(data), hex.EncodeToString(sum[:]), crc32.ChecksumIEEE(data), hex.EncodeToString(sum[:]),
		crc32.ChecksumIEEE(data), hex.EncodeToString(sum[:]))
}

func stubConfig(t *testing.T, dir, id, extra string) string {
	t.Helper()
	text := chipConfig(id, extra)
	for _, region := range []string{"sprites", "sprites_hi", "tiles", "tiles_hi", "samples"} {
		text += fmt.Sprintf("[%s]\nsize = 0\n", region)
	}
	path := filepath.Join(dir, id+".toml")
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		t.Fatal(err)
	}
	return path
}

func TestRunWritesManifestGameConfigAndFileList(t *testing.T) {
	dir := t.TempDir()
	a := stubConfig(t, dir, "alpha", `pref_dir = "alpha-é"`)
	b := stubConfig(t, dir, "beta", "")
	out := filepath.Join(dir, "out")
	args := []string{
		"--configs", a, b, "--output", filepath.Join(out, "rom_manifest.hpp"),
		"--game", "beta", "--game-output", filepath.Join(out, "game.hpp"), "--files-output", filepath.Join(out, "files.txt"),
	}
	var stdout, stderr bytes.Buffer
	if exit := runRoms(args, &stdout, &stderr); exit != 0 {
		t.Fatalf("exit %d: %s", exit, stderr.String())
	}
	if stdout.Len() != 0 || stderr.Len() != 0 {
		t.Errorf("unexpected output %q %q", stdout.String(), stderr.String())
	}
	manifest, _ := os.ReadFile(filepath.Join(out, "rom_manifest.hpp"))
	for _, want := range []string{
		"// Generated by recomp/compile/roms.py. No ROM data.\n#pragma once\n",
		"inline constexpr std::array<Chip, 2> chips_0_rom = {{\n",
		`    { "even.bin", 4, 0x` + fmt.Sprintf("%08x", crc32.ChecksumIEEE([]byte{1, 2, 3, 4})) + "u",
		", 0, 0x0u, \"\", 0, 2, 1, 0, 4, false },\n",
		"inline constexpr std::array<Chip, 0> chips_1_eeprom = {{\n}};\n",
		`    { "alpha", "alpha-\u00e9", { 0, 1, 24, 232, true, false, false }, { false, false }, true, {{ { 8, 8, 0, chips_0_rom }, `,
		"{ 4, 8, 0, chips_0_sound }, { 0, 0, 0, chips_0_samples }, { 0, 0, 0, chips_0_eeprom } }} },\n",
		"inline constexpr std::array<Game, 2> games = {{\n",
		"}};\n} // namespace f3rt::rom_manifest\n",
	} {
		if !strings.Contains(string(manifest), want) {
			t.Errorf("manifest lacks %q", want)
		}
	}
	game, _ := os.ReadFile(filepath.Join(out, "game.hpp"))
	for _, want := range []string{
		"// Generated by recomp/compile/roms.py from games/beta/config.toml. No ROM data.\n",
		"inline constexpr std::string_view id = \"beta\";\n",
		"inline constexpr std::string_view pref_dir = \"beta\";\n",
		"inline constexpr InputConfig input{ false, false };\n",
		"inline constexpr VideoConfig video{ 0, 1, 24, 232, true, false, false };\n",
	} {
		if !strings.Contains(string(game), want) {
			t.Errorf("game config lacks %q", want)
		}
	}
	if files, _ := os.ReadFile(filepath.Join(out, "files.txt")); string(files) != "even.bin\nodd.bin\n" {
		t.Errorf("file list = %q", files)
	}
}

func TestRunKeepsMtimesOfUnchangedOutput(t *testing.T) {
	dir := t.TempDir()
	cfg := stubConfig(t, dir, "alpha", "")
	output := filepath.Join(dir, "hpp")
	args := []string{"--configs", cfg, "--output", output}
	var stdout, stderr bytes.Buffer
	if exit := runRoms(args, &stdout, &stderr); exit != 0 {
		t.Fatalf("exit %d: %s", exit, stderr.String())
	}
	old := time.Now().Add(-time.Hour).Truncate(time.Second)
	if err := os.Chtimes(output, old, old); err != nil {
		t.Fatal(err)
	}
	if exit := runRoms(args, &stdout, &stderr); exit != 0 {
		t.Fatalf("exit %d: %s", exit, stderr.String())
	}
	if info, _ := os.Stat(output); !info.ModTime().Equal(old) {
		t.Error("unchanged manifest was rewritten")
	}
}

func TestRunFailures(t *testing.T) {
	dir := t.TempDir()
	a := stubConfig(t, dir, "alpha", "")
	dup := stubConfig(t, dir, "alpha2", "")
	text, _ := os.ReadFile(dup)
	if err := os.WriteFile(dup, []byte(strings.Replace(string(text), "alpha2", "alpha", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	badVideo := stubConfig(t, dir, "video", "")
	text, _ = os.ReadFile(badVideo)
	if err := os.WriteFile(badVideo, append(text, "[video]\nrotation = 45\n"...), 0o644); err != nil {
		t.Fatal(err)
	}
	out := filepath.Join(dir, "m.hpp")
	tests := []struct {
		name string
		args []string
		exit int
		want string
	}{
		{"duplicate ids", []string{"--configs", a, dup, "--output", out}, 1, "Duplicate game id: alpha"},
		{"bad video", []string{"--configs", badVideo, "--output", out}, 1, "Unsupported video configuration: " + badVideo},
		{"unknown game", []string{"--configs", a, "--output", out, "--game", "nope", "--game-output", out + "2"}, 1, "no config declares game nope"},
		{"game without output", []string{"--configs", a, "--output", out, "--game", "alpha"}, 2, "--game and --game-output go together"},
		{"files without game", []string{"--configs", a, "--output", out, "--files-output", out + "3"}, 2, "--files-output requires --game"},
		{"missing config", []string{"--configs", filepath.Join(dir, "absent.toml"), "--output", out}, 1, "absent.toml"},
		{"no args", nil, 2, "the following arguments are required: --configs, --output"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			exit := runRoms(tt.args, &stdout, &stderr)
			if exit != tt.exit || !strings.Contains(stderr.String(), tt.want) || stdout.Len() != 0 {
				t.Errorf("exit %d, stdout %q, stderr %q", exit, stdout.String(), stderr.String())
			}
		})
	}
}

